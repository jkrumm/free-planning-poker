export interface ChangelogItem {
  text: string
  commit?: { sha: string; href: string }
}

export interface ChangelogSection {
  title: string
  items: ChangelogItem[]
}

export interface Release {
  version: string
  date: string
  compare?: string
  sections: ChangelogSection[]
}

export class ChangelogError extends Error {
  line: number

  constructor(line: number, reason: string, text: string) {
    super(`CHANGELOG.md line ${line}: ${reason}: ${text}`)
    this.name = 'ChangelogError'
    this.line = line
  }
}

const linkedHeading = /^## \[([^\]]+)\]\(([^)]+)\) \((\d{4}-\d{2}-\d{2})\)$/
const plainHeading = /^## (\d+\.\d+\.\d+) \((\d{4}-\d{2}-\d{2})\)$/
const sectionHeading = /^### (.+)$/
const bullet = /^\* (.+)$/
const commitLink = /\s?\(\[([0-9a-f]{7,40})\]\((https?:\/\/[^)]+)\)\)/
const otherLink = /\[([^\]]+)\]\([^)]+\)/g

function parseHeading(line: string, lineNo: number): Release {
  const linked = linkedHeading.exec(line)
  if (linked) {
    const [, version = '', compare = '', date = ''] = linked
    return { version, date, compare, sections: [] }
  }
  const plain = plainHeading.exec(line)
  if (plain) {
    const [, version = '', date = ''] = plain
    return { version, date, sections: [] }
  }
  throw new ChangelogError(lineNo, 'unrecognised release heading', line)
}

function parseItem(body: string): ChangelogItem {
  const text = body.replace(commitLink, '').replace(otherLink, '$1').trim()
  const commit = commitLink.exec(body)
  if (commit === null) return { text }
  const [, sha = '', href = ''] = commit
  return { text, commit: { sha, href } }
}

/**
 * Releases in file order, which is newest first. The changelog is generated by the release tooling. Lines before the
 * first release are prose, and a level-one line is a document title (CHANGELOG.md holds an older one mid-file): both
 * are skipped. A bullet with no section heading, as the releases before 8.3.0 have, goes into an untitled section.
 * A level-two line that is not a release heading fails the parse with its line number.
 */
export function parseChangelog(text: string): Release[] {
  const releases: Release[] = []
  let section: ChangelogSection | undefined
  for (const [index, raw] of text.split('\n').entries()) {
    const lineNo = index + 1
    const line = raw.trimEnd()
    if (line.startsWith('# ')) continue
    if (line.startsWith('## ')) {
      releases.push(parseHeading(line, lineNo))
      section = undefined
      continue
    }
    const current = releases.at(-1)
    if (current === undefined || line === '') continue
    const heading = sectionHeading.exec(line)
    if (heading) {
      section = { title: heading[1] ?? '', items: [] }
      current.sections.push(section)
      continue
    }
    const entry = bullet.exec(line)
    if (entry) {
      if (section === undefined) {
        section = { title: '', items: [] }
        current.sections.push(section)
      }
      section.items.push(parseItem(entry[1] ?? ''))
      continue
    }
    throw new ChangelogError(lineNo, 'unrecognised line in a release', line)
  }
  return releases
}
